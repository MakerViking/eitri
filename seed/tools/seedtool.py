def cmd_check_elf(a) -> None:
    """Every ELF object below --root must be AArch64, must not need a glibc symbol version newer than the image's,
    and every DT_NEEDED library must be shipped in the tree or exist in the image (--sysroot). Static analysis only."""
    root = Path(a.root).resolve()
    readelf = a.readelf or "readelf"
    allowed = {ln.strip() for ln in Path(a.allow_file).read_text().splitlines() if ln.strip() and not ln.startswith("#")} if a.allow_file else None
    external: set[str] = set()
    gmax = tuple(int(x) for x in a.glibc_max.split("."))
    shipped = set()
    for _r, _d, files in os.walk(root):
        shipped.update(files)
    have_image = set()
    if a.sysroot:
        for sub in ("lib", "usr/lib", "lib64", "usr/lib64"):
            d = Path(a.sysroot) / sub
            if d.is_dir():
                have_image.update(p.name for p in d.iterdir())
    problems, checked = [], 0
    worst = (0, 0)
    for dirpath, _dirs, files in os.walk(root):
        for fn in files:
            p = Path(dirpath) / fn
            if p.is_symlink() or not p.is_file():
                continue
            with open(p, "rb") as f:
                head = f.read(64)
            m = elf_machine(head)
            if m is None:
                continue
            rel = p.relative_to(root)
            checked += 1
            if m != 183:
                problems.append(f"{rel}: not AArch64 (e_machine={m})")
                continue
            out = subprocess.run([readelf, "-W", "-d", "-V", str(p)], capture_output=True, text=True).stdout
            for lib in re.findall(r"Shared library: \[([^\]]+)\]", out):
                if lib in shipped:
                    continue
                external.add(lib)
                if allowed is not None and lib not in allowed:
                    problems.append(f"{rel}: needs {lib}, which is neither in the seed nor in requirements/image-libs.txt")
                elif a.sysroot and lib not in have_image:
                    problems.append(f"{rel}: needs {lib}, which the image does not have")
            for maj, mino in re.findall(r"Name: GLIBC_(\d+)\.(\d+)", out):
                v = (int(maj), int(mino))
                worst = max(worst, v)
                if v > gmax:
                    problems.append(f"{rel}: needs GLIBC_{maj}.{mino}, newer than the image's glibc {a.glibc_max}")
    print(f"check-elf: {checked} ELF objects, highest GLIBC_ symbol version needed: {worst[0]}.{worst[1]}, "
          f"libraries expected from the image: {', '.join(sorted(external))}")
    if a.report:
        Path(a.report).write_text(json.dumps({"image_libraries": sorted(external), "glibc_needed": f"{worst[0]}.{worst[1]}",
                                              "elf_objects": checked}, indent=2) + "\n")
    if problems:
        for pr in problems:
            print("FAIL", pr)
        raise SeedError(f"{len(problems)} ELF problem(s)")


# --- finalize ------------------------------------------------------------------------------------------

def read_lock_packages(lock: Path) -> list[dict]:
    return [{"name": n, "version": v} for n, v in seedlib.iter_lock_packages(lock.read_text())]


def cmd_finalize(a) -> None:
    stage = Path(a.stage).resolve()
    out = Path(a.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    facts = json.loads(Path(a.facts).read_text())
    flavor = facts["flavor"]
    version = facts["version"]
    epoch = int(facts["source_date_epoch"])
    req = Path(a.requirements)

    (stage / "eitri").mkdir(parents=True, exist_ok=True)
    (stage / "eitri" / "flavor").write_text(flavor + "\n")
    seed_dir = stage / "eitri" / "seed"
    (seed_dir / "locks").mkdir(parents=True, exist_ok=True)
    lock_files = {
        "klippy": req / f"klippy-{flavor}.txt",
        "moonraker": req / "moonraker.txt",
        "klarity": req / "klarity.txt",
    }
    venvs = {}
    for name, lf in lock_files.items():
        shutil.copyfile(lf, seed_dir / "locks" / f"{name}.txt")
        rep = facts["venvs"][name]
        pkgs = json.loads(Path(rep["packages_json"]).read_text())
        venvs[name] = {
            "lock": f"requirements/{lf.name}",
            "lock_sha256": seedlib.sha256_file(lf),
            "packages": pkgs,
            "built_from_source": rep.get("built_from_source", []),
        }
    chelper = json.loads(Path(facts["chelper_report"]).read_text())
    elf = json.loads(Path(facts["elf_report"]).read_text())

    chso = stage / "firmware" / "klipper" / "klippy" / "chelper" / "c_helper.so"
    seedlib.normalize_tree(stage, epoch)

    # Seed info is written last; the tree digest excludes it.
    tree_digest, entries = seedlib.tree_digest(stage)
    tree_bytes = seedlib.tree_size(stage)
    info = {
        "schema": seedlib.SEED_SCHEMA,
        "kind": "eitri-data-seed",
        "version": version,
        "flavor": flavor,
        "layout": seedlib.LAYOUT_VERSION,
        "source_date_epoch": epoch,
        "target": {
            "arch": "aarch64",
            "python": facts["python_full_version"],
            "python_abi": "cp" + PYTHON_MM.replace(".", ""),
            "interpreter": "/usr/bin/python3",
            "wheel_platform": PLATFORM,
            "glibc_max": facts["glibc_max"],
            "glibc_needed": elf["glibc_needed"],
            "image_libraries": elf["image_libraries"],
        },
        "sources": facts["sources"],
        "venvs": venvs,
        "chelper": chelper | {"compiler": facts["chelper_compiler"]},
        "tree": {
            "algorithm": "sha256 over sorted 'type mode size sha256 path' lines, seed-info.* excluded (SPEC.md)",
            "digest": tree_digest,
            "entries": entries,
            "bytes": tree_bytes,
            "components": list(seedlib.COMPONENTS),
        },
    }
    info["sources"]["klipper_layer"]["tree_sha256"] = seedlib.tree_digest(
        stage, include_prefixes=("eitri/extras", "eitri/klipper-layer"))[0]
    seedlib.write_json(seed_dir / "seed-info.json", info)
    (seed_dir / "seed-info.env").write_text(
        "# Written by the seed build; sourced by sh. See seed/SPEC.md.\n"
        f"SEED_SCHEMA={seedlib.SEED_SCHEMA}\n"
        f"SEED_KIND=eitri-data-seed\n"
        f"SEED_VERSION={version}\n"
        f"SEED_FLAVOR={flavor}\n"
        f"SEED_LAYOUT={seedlib.LAYOUT_VERSION}\n"
        f"SEED_TREE_SHA256={tree_digest}\n"
        f"SEED_TREE_BYTES={tree_bytes}\n"
        f"SEED_FIRMWARE_COMMIT={facts['sources']['firmware']['commit']}\n"
        f"SEED_MOONRAKER_COMMIT={facts['sources']['moonraker']['commit']}\n"
    )
    for f in ("seed-info.json", "seed-info.env"):
        os.chmod(seed_dir / f, 0o644)
    seedlib.normalize_tree(stage, epoch)
    # klippy rebuilds c_helper.so when any source is *newer* than it (chelper/__init__.py: check_build_code).
    os.utime(chso, (epoch + 1, epoch + 1))

    arc_name, man_name = seedlib.seed_names(version, flavor)
    arc = out / arc_name
    tmp_arc = out / (arc_name + ".part")
    seedlib.zstd_compress(lambda fh: seedlib.write_tar(stage, fh), tmp_arc, level=a.level, threads=a.threads)
    os.replace(tmp_arc, arc)

    manifest = dict(info)
    manifest["archive"] = {
        "name": arc_name,
        "sha256": seedlib.sha256_file(arc),
        "size": arc.stat().st_size,
        "uncompressed_size": tree_bytes,
        "compression": "zstd",
        "tar_format": "gnu",
    }
    manifest["created"] = seedlib.iso_utc(int(facts.get("created_epoch", epoch)))
    manifest["info_sha256"] = seedlib.sha256_file(seed_dir / "seed-info.json")
    manifest["builder"] = facts["builder"]
    errs = seedlib.validate_manifest(manifest, archive_name=arc_name)
    if errs:
        raise SeedError("manifest is invalid: " + "; ".join(errs))
    seedlib.write_json(out / man_name, manifest)
    print(arc)
    print(out / man_name)


# --- verify --------------------------------------------------------------------------------------------

def extract_archive(arc: Path, dest: Path) -> None:
    """Extract with GNU tar the way the installers do: mtimes preserved, never `-m`."""
    dest.mkdir(parents=True, exist_ok=True)
    z = subprocess.Popen(["zstd", "-dc", str(arc)], stdout=subprocess.PIPE)
    try:
        t = subprocess.run(["tar", "-xf", "-", "-C", str(dest), "--numeric-owner", "--no-same-owner", "-p"], stdin=z.stdout)
    finally:
        z.stdout.close()
        z.wait()
    if t.returncode != 0 or z.returncode != 0:
        raise SeedError("extracting the archive failed")


def cmd_verify(a) -> None:
    man_path = Path(a.manifest).resolve()
    manifest = seedlib.load_json(man_path)
    arc = man_path.parent / manifest["archive"]["name"] if not a.archive else Path(a.archive)
    problems = []
    mt = seedlib.MANIFEST_RE.match(man_path.name)
    if not mt:
        problems.append(f"manifest file name {man_path.name} does not match data-seed-<version>-<flavor>.manifest.json")
    problems += seedlib.validate_manifest(manifest, archive_name=arc.name)
    if mt and (mt["version"], mt["flavor"]) != (manifest.get("version"), manifest.get("flavor")):
        problems.append("manifest file name disagrees with version/flavor inside it")
    if not arc.exists():
        raise SeedError(f"archive {arc} not found")
    if arc.stat().st_size != manifest["archive"]["size"]:
        problems.append(f"archive size {arc.stat().st_size} != manifest {manifest['archive']['size']}")
    got = seedlib.sha256_file(arc)
    if got != manifest["archive"]["sha256"]:
        problems.append(f"archive sha256 {got} != manifest {manifest['archive']['sha256']}")
    problems += [f"member refused: {m}" for m in seedlib.check_archive(arc)]
    ex = Path(a.extract_to) if a.extract_to else Path(tempfile.mkdtemp(prefix="seed-verify-"))
    try:
        if ex.exists() and any(ex.iterdir()):
            raise SeedError(f"{ex} is not empty")
        extract_archive(arc, ex)
        digest, entries = seedlib.tree_digest(ex)
        t = manifest["tree"]
        if digest != t["digest"] or entries != t["entries"]:
            problems.append(f"tree digest/entries differ: {digest}/{entries} vs {t['digest']}/{t['entries']}")
        info_path = ex / "eitri" / "seed" / "seed-info.json"
        if not info_path.exists():
            problems.append("eitri/seed/seed-info.json missing")
        else:
            if seedlib.sha256_file(info_path) != manifest["info_sha256"]:
                problems.append("seed-info.json does not match manifest.info_sha256")
            info = seedlib.load_json(info_path)
            for k, v in info.items():
                if manifest.get(k) != v:
                    problems.append(f"seed-info.json[{k}] differs from the manifest")
        flavor_file = ex / "eitri" / "flavor"
        if not flavor_file.exists() or flavor_file.read_text().strip() != manifest["flavor"]:
            problems.append("eitri/flavor missing or wrong")
        chdir = ex / "firmware" / "klipper" / "klippy" / "chelper"
        so = chdir / "c_helper.so"
        if not so.exists():
            problems.append("c_helper.so missing")
        else:
            if seedlib.sha256_file(so) != manifest["chelper"]["sha256"]:
                problems.append("c_helper.so sha256 differs from manifest")
            c = read_chelper_constants(chdir / "__init__.py")
            newest = max(os.path.getmtime(chdir / f) for f in c["SOURCE_FILES"] + c.get("OTHER_FILES", []) if (chdir / f).exists())
            newest = max(newest, os.path.getmtime(chdir / "__init__.py"))
            if newest > os.path.getmtime(so):
                problems.append("a chelper source is newer than c_helper.so after extraction: klippy would try to rebuild it")
        for comp in seedlib.COMPONENTS:
            if not (ex / comp).is_dir():
                problems.append(f"component {comp} missing")
        if shutil.which("git"):
            for key, rel in (("firmware", "firmware/klipper"), ("moonraker", "firmware/moonraker")):
                src = manifest["sources"][key]
                g = ["git", "-c", "safe.directory=*", "-C", str(ex / rel)]

                def git(*args):
                    r = subprocess.run([*g, *args], capture_output=True, text=True)
                    return r.stdout.strip() if r.returncode == 0 else f"<git {' '.join(args)} failed: {r.stderr.strip()}>"

                if git("rev-parse", "HEAD") != src["commit"]:
                    problems.append(f"{rel}: HEAD is not {src['commit']}")
                if git("symbolic-ref", "--short", "HEAD") != src["branch"]:
                    problems.append(f"{rel}: not on branch {src['branch']}")
                if git("config", "remote.origin.url") != src["origin"]:
                    problems.append(f"{rel}: origin is not {src['origin']}")
                if git("rev-parse", f"refs/remotes/origin/{src['branch']}") != src["commit"]:
                    problems.append(f"{rel}: origin/{src['branch']} is not the pinned commit")
                if git("describe", "--always", "--tags", "--long", "--dirty") != src["describe"]:
                    problems.append(f"{rel}: git describe is {git('describe', '--always', '--tags', '--long', '--dirty')!r}, manifest says {src['describe']!r}")
                if git("status", "--porcelain", "--untracked-files=all"):
                    problems.append(f"{rel}: git status is not clean after extraction")
                if git("fsck", "--connectivity-only", "--no-progress").startswith("<git"):
                    problems.append(f"{rel}: git fsck failed")
        for lp in ex.rglob("*"):
            if lp.is_symlink():
                t = os.readlink(lp)
                if t.startswith("/data/") and not os.path.lexists(ex / t[len("/data/"):]):
                    problems.append(f"dangling symlink {lp.relative_to(ex)} -> {t}")
                elif not t.startswith("/") and not os.path.lexists(lp.parent / t):
                    problems.append(f"dangling symlink {lp.relative_to(ex)} -> {t}")
    finally:
        if not a.extract_to:
            shutil.rmtree(ex, ignore_errors=True)
    if problems:
        for p in problems:
            print("FAIL", p)
        raise SeedError(f"{len(problems)} problem(s)")
    print(f"ok  {arc.name}  sha256 {got}  {manifest['tree']['entries']} entries, {manifest['archive']['uncompressed_size']} bytes unpacked")


def cmd_emulation_prep(a) -> None:
    """For running the seed under qemu-user: the host kernel follows absolute symlinks on the *host*, so links
    to /data/... are rewritten to the equivalent relative links in this throw-away copy."""
    root = Path(a.data)
    n = 0
    for p in sorted(root.rglob("*")):
        if p.is_symlink():
            t = os.readlink(p)
            if t.startswith("/data/"):
                dest = root / t[len("/data/"):]
                if not os.path.lexists(dest):
                    raise SeedError(f"{p.relative_to(root)} -> {t}: target is not in the seed")
                os.unlink(p)
                os.symlink(os.path.relpath(dest, p.parent), p)
                n += 1
    print(f"emulation-prep: {n} absolute /data symlinks made relative")


