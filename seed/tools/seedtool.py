def sysconfigdata_for_cross(base: Path, out_dir: Path, cc: str, py_include: str, strip_tool: str | None = None) -> str:
    """Write a copy of the target interpreter's _sysconfigdata with the cross compiler and include path
    pointing at build-host locations. Returns the module name (for _PYTHON_SYSCONFIGDATA_NAME)."""
    ns: dict = {}
    exec(compile(base.read_text(), str(base), "exec"), ns)  # a plain dict literal written by CPython's build
    v = dict(ns["build_time_vars"])
    v["CC"] = cc
    v["LDSHARED"] = f"{cc} -shared"
    v["CXX"] = cc.replace("gcc", "g++")
    v["LDCXXSHARED"] = f"{v['CXX']} -shared"
    v["INCLUDEPY"] = py_include
    v["CONFINCLUDEPY"] = py_include
    v["CFLAGS"] = "-fno-strict-overflow -Wsign-compare -DNDEBUG -O2 -g0 -D_FORTIFY_SOURCE=1 -fstack-protector-strong"
    v["OPT"] = "-DNDEBUG -O2 -g0"
    v["PY_CFLAGS"] = v["CFLAGS"]
    v["PY_CFLAGS_NODIST"] = ""
    v["LDFLAGS"] = ""
    # Any remaining host-style absolute path (LIBDIR, LIBPL, ...) is moved under the image's sysroot: the
    # Buildroot compiler wrapper refuses -I/usr/... and -L/usr/... when cross-compiling.
    sysroot = str(Path(py_include).parents[2])
    for k, val in list(v.items()):
        if isinstance(val, str) and (val.startswith("/usr/") or val == "/usr"):
            v[k] = sysroot + val
    name = base.stem
    (out_dir / (name + ".py")).write_text("# generated by seedtool.py; not the interpreter's own file\nbuild_time_vars = " + repr(v) + "\n")
    return name


def cmd_build_wheel(a) -> None:
    """Build a wheel from a source directory with the build env's PEP 517 backend.

    Pure Python (Klarity): plain build. Cross (--cross): the extension modules are compiled with the
    Buildroot toolchain against the image's Python headers, tagged linux_aarch64.
    """
    src, out = Path(a.src).resolve(), Path(a.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    env = uv_env()
    env["SOURCE_DATE_EPOCH"] = str(a.epoch)
    build_py = Path(a.buildenv) / "bin" / "python"
    tmp = Path(tempfile.mkdtemp(prefix="seed-xb-"))
    try:
        if a.cross:
            cc = a.cross_cc
            sysdata = Path(a.sysconfigdata)
            name = sysconfigdata_for_cross(sysdata, tmp, cc, a.py_include)
            env["PATH"] = str(Path(cc).parent) + os.pathsep + env["PATH"]
            env["PYTHONPATH"] = str(tmp)
            env["_PYTHON_SYSCONFIGDATA_NAME"] = name
            env["_PYTHON_HOST_PLATFORM"] = "linux-aarch64"
            env["SETUPTOOLS_EXT_SUFFIX"] = ".cpython-314-aarch64-linux-gnu.so"
            env["CFLAGS"] = f"-I{a.py_include}"
            env["CC"] = cc
            env["LDSHARED"] = f"{cc} -shared"
        before = set(out.glob("*.whl"))
        run([os.environ.get("UV", "uv"), "build", "--wheel", "--no-build-isolation", "--no-config", "--python", build_py, "--out-dir", out, src], env=env)
        new = sorted(set(out.glob("*.whl")) - before)
        if len(new) != 1:
            raise SeedError(f"expected exactly one new wheel in {out}, got {new}")
        whl = new[0]
        if a.cross:
            if "-linux_aarch64" not in whl.name:
                raise SeedError(f"cross-built wheel has an unexpected tag: {whl.name}")
            check_wheel_arch(whl)
            prune_wheel(whl, a.prune or [], a.epoch)
        print(whl)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def elf_machine(data: bytes) -> int | None:
    if data[:4] != b"\x7fELF" or len(data) < 20:
        return None
    return struct.unpack_from("<H", data, 18)[0]


def check_wheel_arch(whl: Path) -> None:
    """Every ELF in a cross-built wheel must be AArch64 (EM_AARCH64 = 183)."""
    n = 0
    with zipfile.ZipFile(whl) as z:
        for name in z.namelist():
            if name.endswith(".so") or ".so." in name:
                m = elf_machine(z.read(name)[:64])
                if m != 183:
                    raise SeedError(f"{whl.name}: {name} is not an AArch64 ELF (e_machine={m})")
                n += 1
    if n == 0:
        raise SeedError(f"{whl.name}: no extension module found in a wheel that was supposed to be compiled")


def prune_wheel(whl: Path, patterns: list[str], epoch: int) -> None:
    """Drop build leftovers (generated C sources) from a wheel and fix its RECORD."""
    if not patterns:
        return
    with zipfile.ZipFile(whl) as zin:
        keep = [i for i in zin.infolist() if not any(fnmatch.fnmatch(i.filename, p) or fnmatch.fnmatch(os.path.basename(i.filename), p) for p in patterns)]
        if len(keep) == len(zin.infolist()):
            return
        tmp = whl.with_suffix(".tmp")
        with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
            record_name = next(i.filename for i in keep if i.filename.endswith(".dist-info/RECORD"))
            names = {i.filename for i in keep}
            for info in keep:
                data = zin.read(info.filename)
                if info.filename == record_name:
                    lines = [ln for ln in data.decode().splitlines() if ln.split(",")[0] in names]
                    data = ("\n".join(lines) + "\n").encode()
                zi = zipfile.ZipInfo(info.filename, date_time=_zip_time(epoch))
                zi.compress_type = zipfile.ZIP_DEFLATED
                zi.external_attr = info.external_attr
                zout.writestr(zi, data)
    tmp.replace(whl)


def _zip_time(epoch: int):
    import time as _t

    t = _t.gmtime(max(epoch, 315532800))
    return (t.tm_year, t.tm_mon, t.tm_mday, t.tm_hour, t.tm_min, t.tm_sec)


def fetch_sdists(sdists: Path, venv: str, dest: Path, offline: bool) -> list[dict]:
    """Download the pinned sdists for one venv into dest (verifying SHA-256) and unpack each into
    dest/<name>-<version>/. Returns one dict per sdist."""
    cfg = tomllib.loads(sdists.read_text())
    dest.mkdir(parents=True, exist_ok=True)
    out = []
    for ent in cfg.get("sdist", []):
        if ent["venv"] != venv:
            continue
        fn = dest / (ent["url"].rsplit("/", 1)[1])
        if not fn.exists() or seedlib.sha256_file(fn) != ent["sha256"]:
            if offline:
                raise SeedError(f"{fn.name} is not cached and --offline was given")
            print(f"downloading {ent['url']}", file=sys.stderr)
            req = urllib.request.Request(ent["url"], headers={"User-Agent": "eitri-seed-build"})
            with urllib.request.urlopen(req, timeout=120) as r, open(str(fn) + ".part", "wb") as f:  # noqa: S310 (https URL pinned in sdists.toml)
                shutil.copyfileobj(r, f)
            os.replace(str(fn) + ".part", fn)
        got = seedlib.sha256_file(fn)
        if got != ent["sha256"]:
            fn.unlink()
            raise SeedError(f"{fn.name}: SHA-256 {got} does not match sdists.toml ({ent['sha256']})")
        srcdir = dest / f"{ent['name']}-{ent['version']}"
        if srcdir.exists():
            shutil.rmtree(srcdir)
        srcdir.mkdir()
        import tarfile

        with tarfile.open(fn) as tar:
            for m in tar.getmembers():
                if m.name.startswith("/") or ".." in m.name.split("/") or not (m.isreg() or m.isdir()):
                    raise SeedError(f"{fn.name}: refusing member {m.name!r}")
            tar.extractall(srcdir, filter="data")
        tops = list(srcdir.iterdir())
        root = tops[0] if len(tops) == 1 and tops[0].is_dir() else srcdir
        out.append({"name": ent["name"], "version": ent["version"], "sdist_sha256": ent["sha256"], "src": root,
                    "prune": ent.get("prune", [])})
    return out


def cmd_build_sdists(a) -> None:
    """Fetch and cross-compile every sdist listed for --venv. Writes a JSON report with the wheel paths."""
    work = Path(a.work)
    items = fetch_sdists(Path(a.sdists), a.venv, work / "sdist", a.offline)
    report = []
    for it in items:
        wheeldir = work / "wheels" / it["name"]
        if wheeldir.exists():
            shutil.rmtree(wheeldir)
        ns = argparse.Namespace(src=str(it["src"]), out=str(wheeldir), buildenv=a.buildenv, epoch=a.epoch, cross=True,
                                cross_cc=a.cross_cc, sysconfigdata=a.sysconfigdata, py_include=a.py_include,
                                prune=it["prune"])
        before = set(wheeldir.glob("*.whl")) if wheeldir.exists() else set()
        cmd_build_wheel(ns)
        new = sorted(set(wheeldir.glob("*.whl")) - before)
        whl = new[0]
        report.append({"name": it["name"], "version": it["version"], "sdist_sha256": it["sdist_sha256"],
                       "wheel": str(whl), "wheel_sha256": seedlib.sha256_file(whl)})
    Path(a.report).write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")


