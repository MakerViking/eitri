def run(cmd, **kw):
    print("+", " ".join(shlex.quote(str(c)) for c in cmd), file=sys.stderr)
    return subprocess.run([str(c) for c in cmd], check=True, **kw)


def uv_env() -> dict:
    env = dict(os.environ)
    env.setdefault("UV_PYTHON_DOWNLOADS", "never")
    env["UV_NO_CONFIG"] = "1"
    env["UV_LINK_MODE"] = "copy"
    env["PYTHONNOUSERSITE"] = "1"
    return env


