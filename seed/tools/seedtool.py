def cmd_compile_bytecode(a) -> None:
    """Pre-compile .py below the given paths with the host interpreter (must be Python 3.14, same bytecode
    magic as the image). co_filename is rewritten to the /data path the file will have on the printer."""
    if sys.version_info[:2] != (3, 14):
        print(f"seedtool: host python is {sys.version_info[0]}.{sys.version_info[1]}, not 3.14: bytecode not "
              "pre-compiled (the printer compiles on first start)", file=sys.stderr)
        return
    stage = Path(a.stage).resolve()
    import compileall
    import py_compile

    for rel in a.paths:
        base = stage / rel
        ok = compileall.compile_dir(str(base), quiet=1, force=True, stripdir=str(stage), prependdir="/data",
                                    invalidation_mode=py_compile.PycInvalidationMode.TIMESTAMP, workers=1)
        if not ok:
            raise SeedError(f"byte-compiling {rel} failed")
        for cache in base.rglob("bin/__pycache__"):
            shutil.rmtree(cache)


# --- chelper -------------------------------------------------------------------------------------------

def read_chelper_constants(init_py: Path) -> dict:
    tree = ast.parse(init_py.read_text())
    want = {"GCC_CMD", "COMPILE_ARGS", "DEST_LIB", "SOURCE_FILES", "OTHER_FILES", "NATIVE_FLAGS", "SSE_FLAGS"}
    found = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name) and node.targets[0].id in want:
            found[node.targets[0].id] = ast.literal_eval(node.value)
    missing = {"GCC_CMD", "COMPILE_ARGS", "DEST_LIB", "SOURCE_FILES"} - set(found)
    if missing:
        raise SeedError(f"{init_py}: could not read {sorted(missing)} (chelper layout changed upstream?)")
    return found


def cmd_chelper(a) -> None:
    """Cross-compile klippy/chelper/c_helper.so exactly the way chelper/__init__.py would, minus -march=native
    (not possible when cross-compiling) and minus debug info. Determinism: fixed random seed, no build id, relative
    paths. The result is made acceptable to klippy by mtime (see SPEC.md, "chelper")."""
    chdir = Path(a.klipper) / "klippy" / "chelper"
    c = read_chelper_constants(chdir / "__init__.py")
    dest = c["DEST_LIB"]
    srcs = c["SOURCE_FILES"]
    args = shlex.split(c["COMPILE_ARGS"] % (dest, " ".join(srcs)))
    args = [x for x in args if x != "-g"]
    cmd = [a.cc, "-mcpu=cortex-a53", "-frandom-seed=eitri-chelper", "-ffile-prefix-map=" + str(chdir) + "=.",
           "-Wl,--build-id=none", *args]
    out = chdir / dest
    if out.exists():
        out.unlink()
    env = dict(os.environ, SOURCE_DATE_EPOCH=str(a.epoch))
    run(cmd, cwd=chdir, env=env)
    if a.strip:
        run([a.strip, "--strip-unneeded", out])
    data = out.read_bytes()
    if elf_machine(data[:64]) != 183:
        raise SeedError(f"{out} is not an AArch64 ELF")
    if a.report:
        Path(a.report).write_text(json.dumps({
            "path": "firmware/klipper/klippy/chelper/c_helper.so",
            "sha256": hashlib.sha256(data).hexdigest(),
            "size": len(data),
            # No build-host paths in anything that ends up in the archive.
            "command": " ".join(shlex.quote(str(x).replace(str(chdir), "$CHELPER")) for x in [os.path.basename(a.cc), *cmd[1:]]),
        }, indent=2, sort_keys=True) + "\n")


