# --- options ---------------------------------------------------------------
def test_defaults_are_valid_and_conservative():
    d = opts.validate({})
    assert d["chamber_heater"] is False          # safety: off unless explicitly enabled
    assert d["channel"] == "eitri"
    assert d["accelerometer"] == "adxl345" and d["klarity_port"] == "/dev/ttyS1"


def test_unknown_and_bad_values_rejected():
    with pytest.raises(opts.ValidationError) as e:
        opts.validate({"nope": 1, "accelerometer": "laser", "camera": "yes", "klarity_port": "/etc/passwd"})
    assert set(e.value.errors) == {"nope", "accelerometer", "camera", "klarity_port"}


def test_chamber_heater_needs_acknowledgement():
    with pytest.raises(opts.ValidationError) as e:
        opts.validate({"chamber_heater": True})
    assert "chamber_ack" in e.value.errors
    ok = opts.validate({"chamber_heater": True, "chamber_ack": True})
    assert ok["chamber_heater"] and ok["chamber_ack"]


def test_ack_cleared_when_chamber_disabled_and_go2rtc_follows_camera():
    v = opts.validate({"chamber_heater": False, "chamber_ack": True, "camera": False, "go2rtc": True})
    assert v["chamber_ack"] is False and v["go2rtc"] is False


