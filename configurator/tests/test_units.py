# --- release.lock -------------------------------------------------------------
def test_release_lock_real_file_and_fallback(tmp_path):
    p = tmp_path / "release.lock"
    p.write_text('[firmware.kalico]\nversion="v9"\ncommit="abcdef0123456789abcdef"\n')
    lock = load(p)
    assert flavor_card(lock, "kalico") == {"version": "v9", "commit": "abcdef0123"}
    assert flavor_card(lock, "klipper") == {"version": "-", "commit": ""}
    assert version(lock, "os", "linux") == "-"
    assert load(tmp_path / "missing") == {}


# --- render ----------------------------------------------------------------------
def make_ctx(**kw):
    lock = load(Settings().release_lock)
    return render.build_context(flavor="klipper", options=opts.validate(kw), detect=None, lock=lock)


def test_printer_cfg_comes_from_the_klipper_layer_and_follows_options(tmp_path):
    s = Settings(data_dir=tmp_path)
    detect = {"boards": [{"role": "mainboard", "port": "/dev/ttyS2"}, {"role": "toolhead", "port": "/dev/ttyS0"}]}
    lock = load(s.release_lock)

    def render_with(**kw):
        ctx = render.build_context(flavor="klipper", options=opts.validate(kw), detect=detect, lock=lock)
        return render.render_all(s, ctx)["printer.cfg"]

    base = render_with()
    assert "[heater_generic chamber]" not in base and "[qd_power_interlock]" not in base
    assert "[qd_plr]" in base and "[adxl345]" in base
    # Layer naming: [mcu] is the toolhead, [mcu U_1] the mainboard, ports come from detection.
    assert "[mcu]\n" in base and base.index("serial: /dev/ttyS0") < base.index("[mcu U_1]") < base.index("serial: /dev/ttyS2")
    on = render_with(chamber_heater=True, chamber_ack=True, power_loss_recovery=False, accelerometer="none")
    assert "[heater_generic chamber]" in on and "[verify_heater chamber]" in on
    assert "[qd_plr]" not in on and "[adxl345]" not in on
    assert base.startswith("# Generated by the Eitri configurator")
    # Runaway protection is not an option: a rendered chamber always carries its verify_heater.
    sections = [l for l in on.splitlines() if l.startswith("[")]
    assert sections.count("[heater_generic chamber]") == sections.count("[verify_heater chamber]") == 1


