def test_printer_cfg_keeps_save_config_block(tmp_path):
    s = Settings(data_dir=tmp_path)
    (s.config_dir).mkdir(parents=True)
    (s.config_dir / "printer.cfg").write_text("[mcu]\nserial: x\n\n#*# <---- SAVE_CONFIG ---->\n#*# [probe]\n#*# z_offset = -0.1\n")
    files = {f["path"]: f for f in render.plan(s, render.render_all(s, make_ctx()))}
    pc = files["printer.cfg"]
    assert pc["status"] == "modified" and pc["foreign"]
    assert pc["new_content"].endswith("#*# z_offset = -0.1\n")
    assert pc["removed"] >= 1 and pc["added"] > 100


def test_write_backs_up_and_second_plan_is_unchanged(tmp_path):
    s = Settings(data_dir=tmp_path)
    s.config_dir.mkdir(parents=True)
    (s.config_dir / "printer.cfg").write_text("old\n")
    ctx = make_ctx()
    rendered = render.render_all(s, ctx)
    res = render.write(s, render.plan(s, rendered))
    assert res["backed_up"] == ["printer.cfg"]
    assert (tmp_path / "printer_data/config/.eitri-backups").is_dir()
    again = render.plan(s, rendered)
    assert all(f["status"] == "unchanged" for f in again)


