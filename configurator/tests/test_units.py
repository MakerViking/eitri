# --- mcuflash adapter ------------------------------------------------------------------
def test_normalize_step_progress_log_result():
    ev = mcuflash.normalize({"type": "step", "step": "probe", "status": "ok", "msg": "x",
                             "data": {"ports": [{"port": "/dev/ttyS0", "state": "klipper", "mcu": "stm32f401xc", "baud": 500000},
                                                {"port": "/dev/ttyS2", "state": "silent"}]}})
    assert ev[0]["phase"] == "identify" and ev[0]["status"] == "done"
    assert [(e["port"], e["state"]) for e in ev[1:]] == [("/dev/ttyS0", "found"), ("/dev/ttyS2", "silent")]
    p = mcuflash.normalize({"type": "progress", "step": "flash", "pct": 140, "board": "toolhead"})[0]
    assert p["percent"] == 100.0 and p["phase"] == "flash"
    f = mcuflash.normalize({"type": "step", "step": "flash", "status": "failed", "board": "toolhead", "msg": "boom", "data": {"recovery": "retry"}})[0]
    assert f["status"] == "fail" and f["recovery"] == "retry"
    chk = mcuflash.normalize({"type": "log", "step": "preflight", "level": "error", "msg": "roles: x",
                              "data": {"id": "roles", "status": "block", "detail": "x", "remedy": "assign"}})[0]
    assert chk["type"] == "check" and chk["remedy"] == "assign"
    live = mcuflash.normalize({"type": "log", "step": "probe", "msg": "m", "data": {"port": "/dev/ttyS0", "state": "katapult"}})
    assert live[1]["type"] == "detect.port" and live[1]["state"] == "found"
    unk = mcuflash.normalize({"type": "wat"})[0]
    assert unk["type"] == "log" and unk["level"] == "debug"


def test_non_phase_steps_become_log_lines():
    ev = mcuflash.normalize({"type": "step", "step": "roundtrip", "status": "ok", "board": "toolhead"})
    assert ev[0]["type"] == "log"
    assert mcuflash.normalize({"type": "step", "step": "rollback", "status": "failed", "board": "toolhead", "msg": "bad"})[0]["level"] == "warn"


PLAN = {
    "blocked": False,
    "ports": [{"port": "/dev/ttyS0", "state": "klipper", "baud": 500000, "mcu": "stm32f401xc", "klipper": {"version": "v0.12.0"}},
              {"port": "/dev/ttyS2", "state": "katapult", "baud": 250000, "mcu": "stm32f401xc"},
              {"port": "/dev/ttyS1", "state": "silent"}],
    "roles": {"mainboard": {"port": "/dev/ttyS0", "confidence": "mapped", "evidence": ["printer.cfg"]},
              "toolhead": {"port": "/dev/ttyS2", "confidence": "verified", "evidence": []}},
    "boards": {"mainboard": {"method": "sdcard-serial"}, "toolhead": {"method": "katapult"}},
    "checks": [{"id": "recovery", "status": "warn", "board": "mainboard", "detail": "stock image acknowledged"}],
}


def test_plan_to_detect_derives_bootloader_from_method():
    d = mcuflash.plan_to_detect(PLAN)
    by = {b["role"]: b for b in d["boards"]}
    assert by["mainboard"]["bootloader"] == "sdcard-serial" and by["mainboard"]["version"] == "v0.12.0"
    assert by["toolhead"]["bootloader"] == "katapult" and by["toolhead"]["chip"] == "stm32f401xc"
    assert d["blockers"] == [] and d["warnings"][0]["code"] == "recovery" and not d["needs_assignment"]


def test_plan_to_detect_blocked_roles_need_assignment_and_unbound_boards_are_unknown():
    plan = {**PLAN, "blocked": True, "roles": {}, "boards": {},
            "checks": [{"id": "roles", "status": "block", "detail": "cannot tell", "remedy": "use --assign"}]}
    d = mcuflash.plan_to_detect(plan)
    assert d["needs_assignment"] and d["blockers"][0]["remedy"] == "use --assign" and d["cli_blocked"]
    assert [b["role"] for b in d["boards"]] == ["unknown", "unknown"]       # two live ports, neither bound


