def test_layer_lookup_order(tmp_path):
    """A copy on /data (shipped by a data bundle) beats the image's <repo_root>/klipper-layer; --layer-dir beats both."""
    import shutil
    from eitri_configurator import layer
    src = Settings().repo_root / "klipper-layer"

    def copy_to(dest):
        for sub in ("config", "scripts"):
            shutil.copytree(src / sub, dest / sub)
        return dest

    image = copy_to(tmp_path / "usr/lib/eitri/klipper-layer")
    s = Settings(data_dir=tmp_path / "data", repo_root=tmp_path / "usr/lib/eitri")
    assert layer.find_layer(s) == image
    data_copy = copy_to(s.eitri_dir / "klipper-layer")
    assert layer.find_layer(s) == data_copy                # a newer layer on /data wins
    s.layer_dir = image
    assert layer.find_layer(s) == image                    # an explicit --layer-dir wins over both
    s.layer_dir = None
    shutil.rmtree(data_copy)
    assert layer.find_layer(s) == image


