"""qd_plr: G-code replay, resume header and state file handling (stdlib only)."""
import json
import os

import pytest

import fakes

plr = fakes.load_extra("qd_plr")

PRINT = b"""; generated by a slicer
EXCLUDE_OBJECT_DEFINE NAME=cube CENTER=100,100
EXCLUDE_OBJECT_DEFINE NAME=ball CENTER=50,50
SET_PRINT_STATS_INFO TOTAL_LAYER=100
PRINT_START BED=60 HOTEND=210
M83
G90
M204 S5000
SET_VELOCITY_LIMIT ACCEL=6000
SET_PRESSURE_ADVANCE ADVANCE=0.032
G92 E0
SET_PRINT_STATS_INFO CURRENT_LAYER=1
EXCLUDE_OBJECT_START NAME=cube
G1 X10 Y20 Z0.2 F6000
G1 X20.5 Y20 E0.8 F1800 ; perimeter
G1 Z0.4
EXCLUDE_OBJECT_END NAME=cube
EXCLUDE_OBJECT_START NAME=ball
SET_PRINT_STATS_INFO CURRENT_LAYER=2
G1 X30 Y40 E0.5
G2 X35 Y45 I5 J0 E0.3
"""


def write(tmp_path, data=PRINT):
    p = tmp_path / "job.gcode"
    p.write_bytes(data)
    return p


def test_scan_reconstructs_toolhead_state(tmp_path):
    p = write(tmp_path)
    st = plr.scan_gcode(str(p), len(PRINT))
    assert (st.pos["X"], st.pos["Y"], st.pos["Z"]) == (35.0, 45.0, 0.4)
    assert st.pos["E"] == pytest.approx(1.6)      # relative moves accumulate
    assert st.feed == 1800.0
    assert st.absolute_xyz and not st.absolute_e and not st.e_is_absolute
    assert st.stats_info == {"TOTAL_LAYER": "100", "CURRENT_LAYER": "2"}
    assert len(st.exclude_defs) == 2
    assert st.exclude_current == "EXCLUDE_OBJECT_START NAME=ball"
    lines = sorted(st.sticky.values())
    assert "M204 S5000" in lines
    assert "SET_VELOCITY_LIMIT ACCEL=6000" in lines
    assert "SET_PRESSURE_ADVANCE ADVANCE=0.032" in lines


def test_scan_stops_at_the_recorded_byte(tmp_path):
    p = write(tmp_path)
    cut = PRINT.index(b"G1 X20.5")
    st = plr.scan_gcode(str(p), cut)
    assert st.pos["X"] == 10.0 and st.pos["Z"] == 0.2
    assert st.exclude_current == "EXCLUDE_OBJECT_START NAME=cube"


def test_relative_modes_and_g92():
    st = plr.ScanState()
    for line in ("G90", "G1 X10 Y10 Z5", "G91", "G1 X5 Z1", "G90", "M82",
                 "G92 E10", "G1 E12.5", "G92 X0"):
        plr.scan_line(st, line)
    assert st.pos == {"X": 0.0, "Y": 10.0, "Z": 6.0, "E": 12.5}
    assert st.e_is_absolute
    plr.scan_line(st, "G91")
    assert not st.e_is_absolute           # relative XYZ makes E relative too
    plr.scan_line(st, "G92")              # bare G92 zeroes everything
    assert st.pos == {"X": 0.0, "Y": 0.0, "Z": 0.0, "E": 0.0}


def record(**kw):
    rec = {"version": 1, "file": "job.gcode", "position": 100,
           "file_size": 1000, "saved_at": 1.7e9, "bed_target": 60.0,
           "extruder_target": 210.0, "chamber_target": 0.0, "fan": 0.5,
           "z_offset": -0.06, "toolhead_z": 0.34,
           "bed_mesh_profile": "adaptive"}
    rec.update(kw)
    return rec


OPTS = {"z_lift": 10., "home_gcode": "G28 X Y", "purge_macro": "QD_PURGE LEN=15",
        "use_interlock": True, "fan_name": "fan_generic cooling_fan",
        "mesh_profile": "adaptive", "z_homed": False}


def header(tmp_path, **rec_kw):
    p = write(tmp_path)
    st = plr.scan_gcode(str(p), len(PRINT))
    return plr.build_resume_header(record(**rec_kw), st, OPTS)


def test_header_sequence(tmp_path):
    lines, warnings = header(tmp_path)
    assert warnings == []
    text = "\n".join(lines)
    order = [text.index(s) for s in (
        "M140 S60", "M190 S60", "SET_KINEMATIC_POSITION Z=0.34 SET_HOMED=z",
        "G28 X Y", "BED_MESH_PROFILE LOAD=adaptive", "M109 S210",
        "QD_PURGE LEN=15", "G1 X35 Y45 F9000", "G1 Z0.4 F600", "G92 E0")]
    assert order == sorted(order)
    # machine Z = gcode Z (0.4) + offset (-0.06), and the offset is restored
    assert "SET_GCODE_OFFSET Z=-0.06 MOVE=0" in lines
    assert "SET_FAN_SPEED FAN=cooling_fan SPEED=0.5" in lines
    assert "EXCLUDE_OBJECT_DEFINE NAME=cube CENTER=100,100" in lines
    assert "EXCLUDE_OBJECT_START NAME=ball" in lines
    assert "SET_PRINT_STATS_INFO CURRENT_LAYER=2 TOTAL_LAYER=100" in lines
    assert "M83" in lines and "G1 F1800" in lines
    # relative extrusion: no absolute E restore
    assert "G92 E0" in lines
    # the nozzle never moves in XY before X/Y are re-homed
    assert text.index("G1 X35") > text.index("G28 X Y")
    # heating the chamber is not requested for a print without one
    assert "QD_SET_CHAMBER" not in text


def test_header_chamber_uses_interlock_when_present(tmp_path):
    lines, _ = header(tmp_path, chamber_target=55.0)
    assert "QD_SET_CHAMBER TARGET=55" in lines
    p = write(tmp_path)
    st = plr.scan_gcode(str(p), len(PRINT))
    no_il = dict(OPTS, use_interlock=False)
    lines, _ = plr.build_resume_header(record(chamber_target=55.0), st, no_il)
    assert "SET_HEATER_TEMPERATURE HEATER=chamber TARGET=55" in lines


def test_header_warns_when_z_does_not_match(tmp_path):
    _, warnings = header(tmp_path, toolhead_z=9.0)
    assert warnings and "differs" in warnings[0]


def test_header_requires_a_known_position(tmp_path):
    p = tmp_path / "early.gcode"
    p.write_bytes(b"PRINT_START BED=60 HOTEND=200\nG28\n")
    st = plr.scan_gcode(str(p), p.stat().st_size)
    with pytest.raises(ValueError, match="restart the print"):
        plr.build_resume_header(record(), st, OPTS)


def test_absolute_extrusion_is_restored():
    st = plr.ScanState()
    for line in ("M82", "G90", "G1 X1 Y2 Z3 E41.25 F900"):
        plr.scan_line(st, line)
    lines, _ = plr.build_resume_header(record(extruder_target=0, bed_target=0,
                                              fan=None, bed_mesh_profile="",
                                              toolhead_z=None),
                                       st, dict(OPTS, purge_macro="",
                                                mesh_profile=None))
    assert "M82" in lines and "G92 E41.25" in lines
    assert not any(ln.startswith(("M140", "M190", "M109", "BED_MESH"))
                   for ln in lines)


def test_atomic_write_and_load_record(tmp_path):
    path = tmp_path / "state.json"
    plr.atomic_write(str(path), json.dumps(record()).encode())
    assert plr.load_record(str(path))["position"] == 100
    assert os.listdir(tmp_path) == ["state.json"]          # no temp left over


@pytest.mark.parametrize("bad", [
    b"not json", b"[]", b"{}",
    json.dumps(record(version=2)).encode(),
    json.dumps(record(file="/etc/passwd")).encode(),
    json.dumps(record(file="../secret.gcode")).encode(),
    json.dumps(record(position=-1)).encode(),
    json.dumps(record(position="7")).encode(),
])
def test_load_record_rejects_garbage(tmp_path, bad):
    path = tmp_path / "state.json"
    path.write_bytes(bad)
    assert plr.load_record(str(path)) is None


def test_load_record_missing_file(tmp_path):
    assert plr.load_record(str(tmp_path / "nope.json")) is None


def test_writer_keeps_only_the_latest(tmp_path):
    path = tmp_path / "state.json"
    w = plr.StateWriter(str(path))
    for i in range(50):
        w.submit(json.dumps(record(position=i)).encode())
    assert w.drain()
    assert plr.load_record(str(path))["position"] == 49
    w.discard()
    assert not path.exists()
    assert os.listdir(tmp_path) == []


# --- tracking state machine (fake Klipper objects) --------------------------

class FakeSd:
    def __init__(self, root):
        self.sdcard_dirname = str(root)
        self.file_position = 0
        self.file_size = 1000
        self._path = None

    def file_path(self):
        return self._path


class FakePrintStats:
    def __init__(self):
        self.state = "standby"

    def get_status(self, eventtime):
        return {"state": self.state,
                "info": {"current_layer": 3, "total_layer": 9}}


class FakeGcodeMove:
    def get_status(self, eventtime):
        return {"homing_origin": (0., 0., -0.05, 0.), "position": (1., 2., 3.4, 0.),
                "speed_factor": 1.0, "extrude_factor": 1.0}


def make_plr(tmp_path):
    printer = fakes.FakePrinter()
    sd = FakeSd(tmp_path)
    stats = FakePrintStats()
    printer.objects.update({
        "virtual_sdcard": sd, "print_stats": stats,
        "gcode_move": FakeGcodeMove(),
        "heaters": fakes.FakeHeaters(
            extruder=fakes.FakeHeater(300., 200., 205.),
            heater_bed=fakes.FakeHeater(125., 60., 60.)),
    })
    cfg = fakes.FakeConfig({"save_interval": 10}, "qd_plr", printer)
    return plr.QdPlr(cfg), sd, stats, tmp_path / ".plr" / "state.json"


def job(sd, tmp_path, pos):
    (tmp_path / "a.gcode").write_text("G1 X1\n" * 100)
    sd._path = str(tmp_path / "a.gcode")
    sd.file_position = pos


def test_tracking_saves_rate_limited_and_clears_on_completion(tmp_path):
    obj, sd, stats, state = make_plr(tmp_path)
    stats.state = "printing"
    job(sd, tmp_path, 120)
    obj._tick(100.)
    assert obj.writer.drain()
    rec = json.loads(state.read_text())
    assert rec["file"] == "a.gcode" and rec["position"] == 120
    assert rec["extruder_target"] == 205.0 and rec["bed_target"] == 60.0
    assert rec["z_offset"] == -0.05 and rec["current_layer"] == 3
    assert not obj.get_status(0)["recovery_available"]       # still printing
    sd.file_position = 240
    obj._tick(105.)                                        # < save_interval
    obj.writer.drain()
    assert json.loads(state.read_text())["position"] == 120
    obj._tick(111.)
    obj.writer.drain()
    assert json.loads(state.read_text())["position"] == 240
    stats.state = "complete"
    obj._tick(112.)
    assert not state.exists() and obj.record is None


@pytest.mark.parametrize("end_state", ["cancelled", "standby"])
def test_cancel_clears_the_record(tmp_path, end_state):
    obj, sd, stats, state = make_plr(tmp_path)
    stats.state = "printing"
    job(sd, tmp_path, 60)
    obj._tick(1.)
    obj.writer.drain()
    assert state.exists()
    stats.state = end_state
    obj._tick(2.)
    assert not state.exists()


def test_error_and_pause_keep_the_record(tmp_path):
    obj, sd, stats, state = make_plr(tmp_path)
    stats.state = "printing"
    job(sd, tmp_path, 60)
    obj._tick(1.)
    obj.writer.drain()
    stats.state = "paused"
    obj._tick(30.)
    assert state.exists()
    stats.state = "printing"
    sd.file_position = 90
    obj._tick(60.)
    stats.state = "error"
    obj._tick(61.)
    obj.writer.drain()
    assert json.loads(state.read_text())["position"] == 90
    stats.state = "standby"                      # klippy restarted after the error
    obj._tick(62.)
    assert state.exists() and obj.get_status(0)["recovery_available"]


def test_existing_record_survives_a_restart_and_is_offered(tmp_path):
    (tmp_path / ".plr").mkdir()
    plr.atomic_write(str(tmp_path / ".plr" / "state.json"),
                     json.dumps(record(file="a.gcode")).encode())
    obj, sd, stats, state = make_plr(tmp_path)
    for cb in obj.printer.handlers["klippy:ready"]:
        cb()
    st = obj.get_status(0)
    assert st["recovery_available"] and st["file"] == "a.gcode"
    assert "Interrupted print: a.gcode" in obj._describe()


def test_resume_requires_confirmation_and_idle_printer(tmp_path):
    (tmp_path / ".plr").mkdir()
    (tmp_path / "a.gcode").write_bytes(PRINT)
    plr.atomic_write(str(tmp_path / ".plr" / "state.json"),
                     json.dumps(record(file="a.gcode", position=len(PRINT))).encode())
    obj, sd, stats, state = make_plr(tmp_path)
    obj.record = plr.load_record(str(state))
    stats.state = "printing"
    with pytest.raises(fakes.ConfigError, match="active"):
        obj.cmd_QD_PLR_RESUME(fakes.FakeGcmd({"CONFIRM": 1}))
    stats.state = "standby"
    gcmd = fakes.FakeGcmd()
    obj.cmd_QD_PLR_RESUME(gcmd)                  # no CONFIRM: explains only
    assert "CONFIRM=1" in gcmd.info[0]
    assert not (tmp_path / ".plr" / "resume-a.gcode").exists()
    assert obj.printer.gcode.scripts == []


