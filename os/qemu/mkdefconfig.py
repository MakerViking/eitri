"""Combine the printer's Buildroot defconfig with qemu.fragment.

    python3 -I mkdefconfig.py BASE_DEFCONFIG FRAGMENT > OUT_DEFCONFIG

Lines of BASE that match a "#DROP <regex>" directive of FRAGMENT are removed, and so is any
BASE line whose option the fragment sets again. The fragment's own lines follow, so the result is a
plain defconfig that Buildroot's "make defconfig" reads.
"""
import re
import sys


def option(line):
    m = re.match(r"^(?:# )?(BR2_[A-Za-z0-9_]+)(?:=| is not set)", line)
    return m.group(1) if m else None


def main(argv):
    if len(argv) != 3:
        sys.exit(__doc__)
    base = open(argv[1], encoding="utf-8").read().splitlines()
    frag = open(argv[2], encoding="utf-8").read().splitlines()
    drops = [re.compile(l[len("#DROP "):].strip()) for l in frag if l.startswith("#DROP ")]
    body = [l for l in frag if not l.startswith("#DROP ")]
    overridden = {option(l) for l in body} - {None}
    out = ["# Generated by os/qemu/mkdefconfig.py from configs/eitri_plus4_defconfig and os/qemu/qemu.fragment.",
           "# Do not edit; change the fragment."]
    dropped = 0
    for line in base:
        if any(d.search(line) for d in drops) or option(line) in overridden:
            dropped += 1
            continue
        out.append(line)
    out.extend(body)
    sys.stdout.write("\n".join(out) + "\n")
    print(f"mkdefconfig: dropped {dropped} base lines", file=sys.stderr)


main(sys.argv)
